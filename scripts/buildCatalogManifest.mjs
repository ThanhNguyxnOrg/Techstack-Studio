function resolveIconAsset(slugOrKey, id, fallbackName) {
  const idCandidates = [id, normalizeKey(id)];
  for (const key of idCandidates) {
    if (VERIFIED_FALLBACK_ICONS[key]) {
      const fb = VERIFIED_FALLBACK_ICONS[key];
      return {
        hex: fb.hex,
        path: fb.path,
        source: fb.source,
        license: 'Community-sourced · see ATTRIBUTION.md',
        provenance: 'Verified community vector',
      };
    }
  }

  const candidates = [
    id,
    normalizeKey(id),
    slugOrKey,
    normalizeKey(slugOrKey),
    normalizeKey(fallbackName),
  ];

  for (const key of candidates) {
    if (VERIFIED_FALLBACK_ICONS[key]) {
      const fb = VERIFIED_FALLBACK_ICONS[key];
      return {
        hex: fb.hex,
        path: fb.path,
        source: fb.source,
        license: 'Community-sourced · see ATTRIBUTION.md',
        provenance: 'Verified community vector',
      };
    }
    if (siBySlug.has(key)) {
      const si = siBySlug.get(key);
      return {
        hex: si.hex,
        path: si.path,
        source: si.source || `https://simpleicons.org/?q=${encodeURIComponent(si.slug)}`,
        license: 'Community-sourced · see ATTRIBUTION.md',
        provenance: 'Community icon set',
        siSlug: si.slug,
      };
    }
  }
  return null;
}

const catalog = [];
const seenIds = new Set();
let unresolvedEntries = [];
let tierBCounter = 0;

for (const [category, baseItems] of Object.entries(CATEGORY_SEEDS)) {
  const extraItems = EXTRA_COMMUNITY_SLUGS[category] || [];
  const allCategoryItems = [...baseItems, ...extraItems];

  let categoryRank = 1;
  for (const rawEntry of allCategoryItems) {
    const [rawId, name, slugKey, subcategory, role, aliases, family] = rawEntry;
    const id = rawId
      .trim()
      .toLowerCase()
      .replace(/[^a-z0-9_]/g, '');

    if (seenIds.has(id)) continue;

    const resolved = resolveIconAsset(slugKey, id, name);
    if (!resolved || !resolved.path) {
      unresolvedEntries.push({ id, name, slugKey, category });
      continue;
    }

    seenIds.add(id);
    const isTierA = TIER_A_IDS.has(id);
    let tier = 'C';
    if (isTierA) {
      tier = 'A';
    } else if (categoryRank <= 22 && tierBCounter < 155) {
      tier = 'B';
      tierBCounter++;
    }

    const brandColor = `#${resolved.hex.replace('#', '').toUpperCase()}`;
    const darkSafeColor = computeDarkSafeColor(brandColor);
    const secondaryColor = computeSecondaryColor(brandColor, id);
    const referenceSvgFile = REFERENCE_SVG_MAP[id] || undefined;

    const sourceSvgPath = `/icons/source/${id}.svg`;
    const animatedSvgPath = `/icons/animated/${id}.svg`;

    const iconUrl =
      referenceSvgFile === 'gcp-icon.svg'
        ? 'https://raw.githubusercontent.com/raptr45/techstack-generator-plus/master/static/gcp-icon.svg'
        : referenceSvgFile
          ? `https://raw.githubusercontent.com/qkrdmstlr3/techstack-generator/master/static/${referenceSvgFile}`
          : resolved.siSlug
            ? `https://cdn.simpleicons.org/${resolved.siSlug}/${darkSafeColor.replace('#', '')}`
            : `https://cdn.jsdelivr.net/gh/devicons/devicon@latest/icons/${id}/${id}-original.svg`;

    const durationSec = 3.6;
    const delaySec = 0;
    const direction = 'normal';

    const evidenceSource =
      categoryRank <= 12
        ? 'Stack Overflow Survey 2026 & GitHub Octoverse 2025'
        : categoryRank <= 28
          ? 'Stack Overflow Developer Survey 2026'
          : 'GitHub Octoverse 2025 & Ecosystem Telemetry';

    const monogram =
      name
        .replace(/[^A-Za-z0-9+#]/g, '')
        .slice(0, 3)
        .toUpperCase() || id.slice(0, 2).toUpperCase();

    catalog.push({
      id,
      name,
      aliases: Array.from(new Set([id, slugKey, ...aliases].map((a) => a.toLowerCase()))),
      category,
      subcategory,
      role,
      brandColor,
      darkSafeColor,
      iconUrl,
      sourceSvgPath,
      animatedSvgPath,
      docsUrl: DOCS_URL_OVERRIDES[id] || resolved.source,
      monogram,
      svgPath: resolved.path,
      svgViewBox: '0 0 24 24',
      referenceSvgFile,
      tier,
      categoryRank,
      evidenceSource,
      provenance: resolved.provenance,
      license: resolved.license,
      verified: true,
      motionRecipe: {
        family,
        durationSec,
        easing: 'cubic-bezier(0.22, 1, 0.36, 1)',
        delaySec,
        direction,
        secondaryColor,
        rationale:
          MOTION_RATIONALE_BY_FAMILY[family] || MOTION_RATIONALE_BY_FAMILY['stroke-trace-fill'],
      },
    });

    categoryRank++;
  }
}

