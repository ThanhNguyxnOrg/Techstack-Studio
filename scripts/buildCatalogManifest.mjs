// Helper to ensure dark-mode legibility while keeping brand identity
function computeDarkSafeColor(hex) {
  const clean = hex.replace('#', '');
  const r = parseInt(clean.slice(0, 2), 16) || 0;
  const g = parseInt(clean.slice(2, 4), 16) || 0;
  const b = parseInt(clean.slice(4, 6), 16) || 0;
  // Relative luminance approximation
  const lum = (0.299 * r + 0.587 * g + 0.114 * b) / 255;
  if (lum >= 0.26) {
    return `#${clean.toUpperCase()}`;
  }
  // Boost brightness towards alabaster/cyan/brand tint so dark logos (#000000, #181717, #003B57) are crisp on #0B0D10
  if (r === g && g === b) {
    return '#F3F1EC';
  }
  const boost = (c) => Math.min(255, Math.round(c + (255 - c) * 0.58));
  const toHex = (c) => boost(c).toString(16).padStart(2, '0').toUpperCase();
  return `#${toHex(r)}${toHex(g)}${toHex(b)}`;
}

// Compute complementary/harmonic secondary color for dual-tone SVG animations
function computeSecondaryColor(hex, id) {
  const specials = {
    python: '#FFD43B',
    javascript: '#FFF380',
    typescript: '#93C5FD',
    react: '#E0F2FE',
    docker: '#93C5FD',
    pytorch: '#FDBA74',
    rust: '#FDE68A',
    go: '#BAE6FD',
    kubernetes: '#93C5FD',
    postgresql: '#93C5FD',
    redis: '#FCA5A5',
    arduino: '#99F6E4',
    vuejs: '#35495E',
    svelte: '#FED7AA',
  };
  if (specials[id]) return specials[id];
  const clean = hex.replace('#', '');
  const r = parseInt(clean.slice(0, 2), 16) || 0;
  const g = parseInt(clean.slice(2, 4), 16) || 0;
  const b = parseInt(clean.slice(4, 6), 16) || 0;
  const tint = (c) => Math.min(255, Math.round(c + (255 - c) * 0.52));
  const toHex = (c) => tint(c).toString(16).padStart(2, '0').toUpperCase();
  return `#${toHex(r)}${toHex(g)}${toHex(b)}`;
}

